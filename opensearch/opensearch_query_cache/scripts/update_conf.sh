#!/usr/bin/env bash
###################################################
#
# file: update_conf.sh
#
# Regenerate config/opensearch.yml and
# config/jvm.options.d/experiment.options for one
# Lucene query-cache configuration.
#
# Usage:
#   ./update_conf.sh <conf_index> <mode>
#
# mode:
#   onheap | teraheap
#
###################################################

set -euo pipefail

SCRIPT_DIR=$(
    cd "$(dirname "${BASH_SOURCE[0]}")"
    pwd
)

source "${SCRIPT_DIR}/conf.sh"

CONF_IDX="${1:?usage: update_conf.sh <conf_index> <mode>}"
MODE="${2:?usage: update_conf.sh <conf_index> <mode>}"

if ! [[ "${CONF_IDX}" =~ ^[0-9]+$ ]]; then
    echo "update_conf.sh: conf_index must be a non-negative integer" >&2
    exit 1
fi

if [ "${CONF_IDX}" -ge "${#H1_SIZE[@]}" ]; then
    echo "update_conf.sh: conf_index ${CONF_IDX} is outside H1_SIZE" >&2
    exit 1
fi

if [ "${CONF_IDX}" -ge "${#QUERY_CACHE_SIZE[@]}" ]; then
    echo "update_conf.sh: conf_index ${CONF_IDX} is outside QUERY_CACHE_SIZE" >&2
    exit 1
fi

case "${MODE}" in
    onheap|teraheap) ;;
    offheap)
        echo "update_conf.sh: offheap request-cache mode is not valid for Lucene query-cache experiments" >&2
        exit 1
        ;;
    *)
        echo "unknown mode: ${MODE} (expected onheap|teraheap)" >&2
        exit 1
        ;;
esac

H1="${H1_SIZE[$CONF_IDX]}"
CACHE="${QUERY_CACHE_SIZE[$CONF_IDX]}"

H1H2=""
if [ "${MODE}" == "teraheap" ]; then
    if [ "${#H1_H2_SIZE[@]}" -eq 0 ]; then
        echo "update_conf.sh: H1_H2_SIZE is empty" >&2
        exit 1
    fi

    if [ "${CONF_IDX}" -lt "${#H1_H2_SIZE[@]}" ]; then
        H1H2="${H1_H2_SIZE[$CONF_IDX]}"
    else
        last_h1h2=$(( ${#H1_H2_SIZE[@]} - 1 ))
        H1H2="${H1_H2_SIZE[$last_h1h2]}"
    fi

    if [ "${H1H2}" -le "${H1}" ]; then
        echo "update_conf.sh: H1_H2_SIZE (${H1H2}G) must be larger than H1 (${H1}G)" >&2
        exit 1
    fi
fi

YML="${OPENSEARCH_DIR}/config/opensearch.yml"
JVM_D="${OPENSEARCH_DIR}/config/jvm.options.d"
JVM_OPTS="${JVM_D}/experiment.options"

mkdir -p "${JVM_D}"
mkdir -p "${MNT_DATA}/opensearch-logs"
rm -f "${JVM_OPTS}"

###################################################
# opensearch.yml
###################################################

cat > "${YML}" <<YAMLEOF
# Generated by update_conf.sh -- do not edit.
# mode=${MODE} conf=${CONF_IDX} H1=${H1}G query_cache=${CACHE}

cluster.name: teraheap-eval
node.name: node-1

network.host: sith4
http.port: 9200

discovery.type: single-node

path.data: ${MNT_DATA}/opensearch-data
path.logs: ${MNT_DATA}/opensearch-logs

# Lucene node query cache. This is the cache exercised by bbox.
indices.queries.cache.size: ${CACHE}
indices.queries.cache.count: 100000
indices.requests.cache.size: 0mb
knn.memory.circuit_breaker.limit: 10gb
YAMLEOF

###################################################
# jvm.options.d/experiment.options
###################################################

{
    echo "# Generated by update_conf.sh -- mode=${MODE} conf=${CONF_IDX}"
    echo

    if [ "${MODE}" == "teraheap" ]; then
        mkdir -p "${MNT_H2}"

        echo "-Xmx${H1H2}g"
        echo "-server"
        echo "-XX:+UseG1GC"
        echo "-XX:-ClassUnloading"
        echo "-XX:+EnableTeraHeap"
        echo "-XX:TeraHeapSize=$(((H1H2 - H1) * 1024 * 1024 * 1024))"
        echo "-Xms${H1}g"
        echo "-XX:TeraStripeSize=${STRIPE_SIZE}"
        echo "-XX:AllocateH2At=${MNT_H2}/"
        echo "-XX:H2FileSize=$((H2_FILE_SZ * 1024 * 1024 * 1024))"
        echo "-XX:+TeraHeapStatistics"
        echo "-XX:G1HeapRegionSize=16m"
        echo "-Xlogth:${MNT_DATA}/opensearch-logs/teraheap.txt"
        echo "-Dopensearch.insecure.allow.security.manager.disable=true"
    else
        echo "-Xms${H1}g"
        echo "-Xmx${H1}g"
        echo "-XX:+UseG1GC"
        echo "-XX:G1HeapRegionSize=16m"
    fi

    echo
    echo "-XX:-UseCompressedOops"
    echo "-XX:-UseCompressedClassPointers"
    echo "-XX:ParallelGCThreads=${GC_THREADS}"

    echo
    echo "# One GC log per JVM instance."
    echo "-Xlog:gc*:file=${MNT_DATA}/opensearch-logs/gc-%p.log:utctime,pid,tags"

    echo
    echo "--add-opens=jdk.unsupported/sun.misc=ALL-UNNAMED"

    if [ -n "${USER_EXTRA_JAVA_OPTS}" ]; then
        echo
        echo "${USER_EXTRA_JAVA_OPTS}"
    fi
} > "${JVM_OPTS}"

###################################################
# Disable heap/GC-log options shipped in the base
# jvm.options so experiment.options is authoritative.
###################################################

sed -i \
    's/^-Xms[0-9].*$/# &  (overridden in jvm.options.d)/' \
    "${OPENSEARCH_DIR}/config/jvm.options"

sed -i \
    's/^-Xmx[0-9].*$/# &  (overridden in jvm.options.d)/' \
    "${OPENSEARCH_DIR}/config/jvm.options"

sed -i \
    's/^\([0-9]*-\?:\)\?-Xlog:gc.*$/# &  (overridden in jvm.options.d)/' \
    "${OPENSEARCH_DIR}/config/jvm.options"

exit 0
